        tds = tr.find_all("td")
        if len(tds) < 2:
            continue
        month_txt = (ths[0].get_text(strip=True) if ths
                     else tds[0].get_text(strip=True))   # e.g. "8/2026"
        val_txt = tds[0].get_text(strip=True)            # e.g. "5,0602" (Estadual)
        m = _re.match(r"^(\d{1,2})/(\d{4})$", month_txt)
        if not m:
            continue
        try:
            brl = float(val_txt.replace(".", "").replace(",", "."))
        except Exception:
            continue
        if not (1 < brl < 50):   # 过滤明显异常（Agrolink 早期数据有 67~155 录入错误）
            continue
        ym = "%s-%02d" % (m.group(2), int(m.group(1)))
        return brl, ym
