def _with_timeout(fn, timeout, default=None):
    """在子线程跑 fn，超时返回 default（用于防止网络阻塞卡死整条流程）。"""
    res=[default]; ev=threading.Event()
    def _run():
        try: res[0]=fn()
        except Exception: res[0]=default
        ev.set()
    t=threading.Thread(target=_run, daemon=True); t.start()
    ev.wait(timeout)
    return res[0]


