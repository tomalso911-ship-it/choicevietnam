def _gf_parse(html):
    """解析 GREENFEED 表格，返回 {region: {col_key: current_vnd}}。
    真实结构（2026-08 用完整页面数据破译确认）：
      - 每个区域是一行 <tr>，td 文本连写后为 **13 个数字**：
        LIVE PIG(cur, prev, chg) + 其余五列各 (cur, chg) 二元组：
          pig=57,750/56,500/-500 │ duck=47,500/500 │ native=42,833/-833
          broiler=28,250/-1,000 │ egg(枚)=1,735/-118 │ duck_egg(枚)=2,240/-38
      - 变化量可能为 0 或负数（去标签后负号丢失），禁止按 >=100 过滤。
      - 页面还有第二张 BREEDS 表（鸭苗/鸡苗价），首列同样是猪价，易混淆——
        故只在包含 'LIVE PIG' 与 'CHICKEN EGG' 的第一张 LIVESTOCK PRODUCTS 表内解析。"""
    out = {}
    for tbl in re.findall(r"<table\b.*?</table>", html, re.S | re.I):
        up = re.sub(r"<[^>]+>", " ", tbl).upper()
        if "LIVE PIG" not in up or "CHICKEN EGG" not in up:
            continue
        rows = re.findall(r"<tr\b[^>]*>(.*?)</tr>", tbl, re.S | re.I)
        for row in rows:
            cells = re.findall(r"<t[dh]\b[^>]*>(.*?)</t[dh]>", row, re.S | re.I)
            texts = [HT.unescape(re.sub(r"<[^>]+>", " ", c)) for c in cells]
            flat = " ".join(texts).upper()
            reg = next((r for r in _GF_REGIONS if r in flat), None)
            if not reg:
                continue
            nums = []
            for t in texts:
                for mch in re.findall(r"-?\d[\d,]*(?:\.\d+)?", t):
                    nums.append(abs(float(mch.replace(",", ""))))
            # 期望 13 个：pig(0,1,2) + duck(3,4) + native(5,6) + broiler(7,8)
            #             + egg(9,10) + duck_egg(11,12)；current 固定在偶组首位
            if len(nums) < 13:
                continue
            g = nums[:13]
            # setdefault：同一区域若已在主表解析出，忽略页面上后出现的重复副本表
            out.setdefault(reg, {
                "pig": g[0], "duck": g[3], "chicken_native": g[5],
                "chicken_broiler": g[7], "egg": g[9], "duck_egg": g[11],
            })
    return out

