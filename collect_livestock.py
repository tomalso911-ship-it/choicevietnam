def _thb_rate(ym):
    """THB per USD：本地 World Bank 年均优先（FX_LCU_PER_USD['THB']，随 _load_fx 加载），
    缺当年时 frankfurter.app 月均兜底，最后 33.0 常数兜底。进程内按月缓存。"""
    if ym in _THB_RATE_CACHE:
        return _THB_RATE_CACHE[ym]
    rate = None
    # 1) 本地年均价（与 CN/VN 同源同口径）
    fx_th = FX_LCU_PER_USD.get("THB") or {}
    y = ym[:4]
    r0 = fx_th.get(y) or fx_th.get(int(y) if y.isdigit() else y)
    if r0 and 25 < float(r0) < 50:
        rate = float(r0)
    # 2) frankfurter 月均兜底
    if not rate:
        try:
            def _do():
                yy, m = int(ym[:4]), int(ym[5:7])
                last_day = [31,29 if yy%4==0 and (yy%100!=0 or yy%400==0) else 28,
                            31,30,31,30,31,31,30,31,30,31][m-1]
                url = ("https://api.frankfurter.app/%s-01..%s-%02d?from=USD&to=THB"
                       % (ym, ym, last_day))
                import json as _json
                txt = _http_text(url, 15)
                data = _json.loads(txt).get("rates", {})
                vals = [v["THB"] for v in data.values() if v.get("THB")]
                return (sum(vals)/len(vals)) if vals else None
            r1 = _with_timeout(_do, 20, default=None)
            if r1 and 25 < r1 < 50:
                rate = r1
        except Exception:
            pass
    # 3) 常数兜底（近年 USDTHB 30~37）
    if not rate:
        rate = 33.0
    _THB_RATE_CACHE[ym] = rate
    return rate

def _cpf_week_links():
    """从列表页抓周报文章链接（slug 型，如 /en/media-center/industrial-<泰文slug>；
    也有旧数字型 ID）。返回绝对 URL 列表，仅保留含周报特征的页面地址。
    实测：列表页 href 即为 slug 全链；旧数字 ID 已停用。"""
    try:
        html = _http_text_retry(_CPF_LIST_URL, 18)
    except Exception:
        return []
    raw = re.findall(r'href="([^"]*?/media-center/[^"]+)"', html)
    out, seen = [], set()
    for l in raw:
        if l.startswith("/"):
            l = "https://www.cpfworldwide.com" + l
        if l in seen:
            continue
        seen.add(l)
        # 周报页均为 industrial- 前缀（泰文 slug 已 URL 编码）；排除 goodhealth/livestock-ok 等非周报
        if "/media-center/industrial-" in l and "goodhealth" not in l and "livestock-ok" not in l:
            out.append(l)
    return out

def _fetch_th_cpf(item, ym):
    """CPF 周报聚合：扫周报页，取 Period 在 ym 内的 生猪/肉鸡 farm-gate THB 读数平均，
    THB→USD 后返回 USD/kg（月均）。无命中返回 None（该月走 carry 补全）。
    注意：实测 CPF 周报自 2026-03-13 后停更；恢复发布时本函数自动恢复工作。"""
    if not ONLINE_FETCH:
        return None
    def _do():
        rate = _thb_rate(ym)
        if not rate:
            return None
        vals = []
        for url in _cpf_week_links():
            try:
                html = _http_text_retry(url, 15)
            except Exception:
                continue
            txt = re.sub(r"<[^>]+>", " ", html)
            txt = re.sub(r"\s+", " ", txt)
            mp = re.search(r"Period:\s*(\d{1,2})\s*[–\-]\s*(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})", txt)
            if not mp:
                continue
            mon = _TH_MONTHS.get(mp.group(3).lower())
            if not mon:
                continue
            week_ym = "%s-%02d" % (mp.group(4), mon)
            if week_ym != ym:
                continue
            if item == "pig":
                m = re.search(r"reference price[^.]{0,200}?to\s*([\d,]+)\s*baht/kg", txt, re.I)
            else:
                m = re.search(r"farm-?gate price for broilers[^.]{0,200}?is\s*([\d,]+)\s*baht/kg", txt, re.I)
            if m:
                vals.append(float(m.group(1).replace(",", "")))
        if not vals:
            return None
        thb = sum(vals) / len(vals)
        usd = thb / rate
        return round(usd, 4) if 0 < usd < 12 else None
    try:
        return _with_timeout(_do, 40, default=None)
    except Exception:
        return None

def _fetch_th_egg(item, ym):
    """泰国鸡蛋出场价(THB/枚)：新闻事件驱动，约每月一调。
    v1 用 Google News RSS 标题抽取 baht 数值，取 ym 内最后一条；无更新返回 None
    （曲线按 carry 语义沿用上月，正合'无更新则沿用'）。"""
    if not ONLINE_FETCH:
        return None
    def _do():
        rate = _thb_rate(ym)
        if not rate:
            return None
        import xml.etree.ElementTree as _ET
        url = ("https://news.google.com/rss/search?q=Thailand+farm-gate+egg+price+baht"
               "&hl=en-US&gl=US&ceid=US:en")
        txt = _http_text_retry(url, 15)
        root = _ET.fromstring(txt.encode("utf-8"))
        best = None  # (date_str, thb)
        for it in root.iter("item"):
            title = (it.findtext("title") or "")
            pub = (it.findtext("pubDate") or "")
            mm = re.search(r"(\d\.\d{1,2})\s*(?:baht|฿)", title, re.I)
            if not mm:
                continue
            # pubDate: 'Wed, 06 Aug 2026 ...'
            dp = re.search(r"(\d{1,2})\s+([A-Za-z]{3})\s+(\d{4})", pub)
            if not dp:
                continue
            mon3 = {"jan":1,"feb":2,"mar":3,"apr":4,"may":5,"jun":6,
                    "jul":7,"aug":8,"sep":9,"oct":10,"nov":11,"dec":12}.get(dp.group(2).lower())
            if not mon3:
                continue
            d_ym = "%s-%02d" % (dp.group(3), mon3)
            if d_ym != ym:
                continue
            thb = float(mm.group(1))
            if 2.0 <= thb <= 8.0 and (best is None or pub >= best[0]):
                best = (pub, thb)
        if not best:
            return None
        thb_kg = best[1] * _EGGS_PER_KG_TH
        usd = thb_kg / rate
        return round(usd, 4) if 0 < usd < 12 else None
    try:
        return _with_timeout(_do, 30, default=None)
    except Exception:
        return None

