    ap.add_argument("--import-manual",action="store_true",help="读 livestock_manual_prices.csv 导入用户手工真值(含菲律宾等补录)")
    ap.add_argument("--incremental",action="store_true",help="增量模式：仅延伸到当前月，保留历史 collected 点")
