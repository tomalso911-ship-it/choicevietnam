def _agro_clean(html):
    t = re.sub(r"<[^>]+>", " ", html)
    t = re.sub(r"\s+", " ", t)
    return HT.unescape(t)

def _agro_fetch(url, timeout=18):
    return _http_text_retry(url, timeout)

def _agro_extract_near(text, kws, lo, hi):
    """在 text 中找 keywords 上下文窗口内的 'XX.XXX đồng/kg'，落在 [lo,hi] 区间的取为出栏价。"""
    vals = []
    for m in re.finditer(r"(\d[\d\.,]*)\s*đồng/kg", text):
        s = text[max(0, m.start() - 55):m.start()]
        if any(k in s.lower() for k in kws):
            try:
                v = float(m.group(1).replace(".", "").replace(",", ".")) if "," in m.group(1) else float(m.group(1))
            except ValueError:
                continue
            if lo <= v <= hi:
                vals.append(v)
    return vals

def _agro_latest_articles():
    """从 agro.gov.vn 肉食品栏目页发现最新畜牧行情文章链接（返回 URL 列表，最新在前）。"""
    html = _agro_fetch("https://agro.gov.vn/vn/xc6_Thit-va-thuc-pham.html", 18)
    links = re.findall(r'\.\./vn/(tID\d[^"\']+\.html)', html)
    seen, out = set(), []
    for l in links:
        if l not in seen:
            seen.add(l)
            out.append("https://agro.gov.vn/vn/" + l)
    return out

def _fetch_vn_price(item, ym):
    """通用：抓 agro.gov.vn 最新畜牧行情文章，按品种关键词+区间提取出栏价(đồng/kg)→USD/kg。
    返回 USD/kg 或 None。ym 用于定位当年 VND/USD 汇率。"""
