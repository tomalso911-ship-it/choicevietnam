    print("[collect] 写入 retail 原始记录 %d 条" % len(retail_rows))
    # 记录实际 range 到 meta（便于前端/增量判断）
    conn.execute("INSERT OR REPLACE INTO livestock_meta(key,value) VALUES('range_end',?)", (eff_end,))
    conn.commit()
    return conn, labels


