def br_egg(ym):
    """返回巴西鸡蛋出厂价(出栏价) USD/kg。
    口径修正：boca/mercadodoovo 抓到的是「市场/批发价(R$/caixa 30dz)」，不是出栏价，
    故按方法论 B 段做 retail_backout：出栏价 = 市场价 / (1 + MARKUP['egg']=30%)。
    季节性：以抓到的「观察月真实价」为基准，按 _BR_EGG_SEASONAL 月系数缩放到目标月，
            使每个月的自动更新都带旺季/淡季价差关系（2-3月高、1月最低、7/11次低）。
    主源 boca.com.br（公开，每日更新）→ 备源 mercadodoovo.com.br（公开历史约上月）
    → 都失败返回 None，由 build() 回退 user_historical_br 锚点/last 值。"""
    if not ONLINE_FETCH:
        return None
    def _do():
        brl_caixa, ref_ym = _br_egg_from_boca()
        if brl_caixa is None:
            brl_caixa, ref_ym = _br_egg_from_mercadodoovo()
        if brl_caixa is None or ref_ym is None:
            return None
        # 1) caixa → kg（市场价，R$/kg）
        brl_per_kg = brl_caixa / _BR_EGG_KG_PER_CAIXA
        # 2) 市场价 → 出栏价（retail_backout，鸡蛋 +30% 加价）
        farmgate_brl = brl_per_kg / (1 + MARKUP["egg"])
        # 3) 季节性缩放：目标月相对观察月
        factor = _br_egg_seasonal_factor(ym, ref_ym)
        farmgate_brl *= factor
        # 4) BRL → USD
        usd = farmgate_brl / _brl_rate(ym)
        return round(usd, 4) if 0.3 < usd < 5 else None
    # 快速失败：boca/mercadodoovo 各 10s 内返回，整体 14s 上限，失败即回退锚点，避免月度任务挂起。
    try:
        return _with_timeout(_do, 14, default=None)
    except Exception:
        return None

