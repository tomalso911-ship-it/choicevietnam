def _fetch_oecd_shape(item, ccode):
    """抓取 OECD CPI 分项指数（2015=100），返回 {ym: index} 作为形状参考。失败返回 {}。"""
    if not ONLINE_FETCH:
        return {}
    c = OECD_COUNTRY.get(ccode); s = OECD_SERIES.get(item)
    if not c or not s: return {}
    url = ("https://stats.oecd.org/sdmx-json/data/PRICES_CPI/.%s.%s?startPeriod=2021&endPeriod=2026&format=json"
           % (c, s))
    try:
        d = _with_timeout(lambda: _http_json(url, 15), 18, default=None)
        if not d: return {}
        out={}
        # SDMX-JSON: structure.dataSets[0].series -> observations
        ds = d.get("dataSets",[{}])[0]
        series = ds.get("series",{}) if isinstance(ds,dict) else {}
        for sk,sv in series.items():
            obs = sv.get("observations",{})
            for pos,val in obs.items():
                # pos 对应 time dimension 索引
                v = val[0] if isinstance(val,list) else val
                out[pos]=float(v)
        # 映射 time 索引 -> ym
        dims = d.get("structure",{}).get("dimensions",{}).get("observation",[])
        tdim = dims[0] if dims else {}
        tvals = tdim.get("values",[]) if isinstance(tdim,dict) else []
        res={}
        for pos,idx in out.items():
            try:
                tv = tvals[int(pos)]
                per = tv.get("id") or tv.get("name")
                # per 形如 2021-01 或 2021-M01
                ym = per.replace("-M","-")[:7]
                res[ym]=idx
            except Exception:
                pass
        return res
    except Exception as e:
        print("  [oecd] %s/%s skip: %s" % (ccode,item,repr(e)[:80]))
        return {}

