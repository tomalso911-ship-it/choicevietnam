# ============ 倒推 + 补全 并生成 farmgate ============
def derive_farmgate(conn, labels):
    # 预取 OECD 形状（仅 JP/KR/AU 用其作为季节形状，绝对水平用锚点校准）
    shape_cache={}
    for cc in ("JP","KR","AU"):
        for item in ITEMS:
            shape_cache[(item,cc)] = _fetch_oecd_shape(item, cc)

    # 国家 → 汇率函数（用于公式文本，forecast 里不需要）
    rate_funcs = {"PH": _php_rate, "ID": _idr_rate, "TH": _thb_rate}

    for item in ITEMS:
        mk = MARKUP[item]
        for cc in COUNTRIES:
            src = RETAIL_SOURCES[(item,cc)]
            src_method = src["method"]
            src_url = src["source_url"]

            # ---------- forecast 方法（无 retail 源，直接预测未来） ----------
            if src_method == "forecast":
                _derive_forecast(conn, labels, item, cc, src_url)
                continue

            # ---------- stop 方法：明确停止更新，不生成任何数据（含预测） ----------
            if src_method == "stop":
                continue

            # ---------- 正常 retail 源：direct / inverse / markup ----------
            rows = conn.execute("""SELECT ym,price_usd,unit,note FROM livestock_retail
                WHERE item=? AND country=? ORDER BY ym""", (item,cc)).fetchall()
            series={}
            for ym,usd,unit,note in rows:
                if usd is None: continue
                # inverse 已在 build 里按国家系数+汇率倒推为 farmgate USD/kg；direct 即为 farmgate
                if src_method in ("direct", "inverse"):
                    fg = usd
                else:
                    fg = usd / (1 + mk)
                series[ym] = (round(fg, 4), note)
            # 无真实值时，用 OECD 形状×锚点水平 作为种子（JP/KR/AU）
            if not series and cc in shape_cache:
                shp = shape_cache[(item,cc)]
                if shp:
                    anchor = ANCHOR_USD[item][cc]
                    vs = list(shp.values())
                    base = sum(vs)/len(vs) if vs else 100.0
                    for ym in labels:
                        if ym in shp and shp[ym] and base:
                            lvl = anchor * (shp[ym]/base)
                            series[ym]=(round(lvl,4), "oecd_shape_anchor")
            # 断点补全
            filled = _gap_fill_simple(series, labels, item, cc)
            for ym in labels:
                fg, method, formula_txt = filled[ym]
                # 「真值锁死，推算可升级」：已落库月份若 method='collected' 绝不覆盖（页面不跳）；
                # 若是 gap_fill/anchor 等推算值，则允许被重新推导的结果升级覆盖
                # （这样月初先出现的插值不会被月末才发布的真实数据永久卡住）。
                conn.execute("""INSERT INTO livestock_farmgate
                    (item,country,ym,price_usd,method,formula,source_url)
                    VALUES(?,?,?,?,?,?,?)
                    ON CONFLICT(item,country,ym) DO UPDATE SET
                        price_usd=excluded.price_usd, method=excluded.method,
                        formula=excluded.formula, source_url=excluded.source_url
                    WHERE livestock_farmgate.method != 'collected'""",
                    (item,cc,ym,fg,method,formula_txt,src_url))
    conn.commit()
    print("[collect] farmgate 推导+补全完成")


def _derive_forecast(conn, labels, item, cc, src_url):
    """对 method='forecast' 的 (item,cc) 生成预测 farmgate（虚线显示）。
    策略：用已有真实 farmgate 最后 6 个月做线性外推；若无历史，用 ANCHOR_USD 兜底。
    只从历史最后一个月之后开始生成预测，历史段不动。
    """
    hist = conn.execute("""SELECT ym, price_usd FROM livestock_farmgate
        WHERE item=? AND country=? AND method IN ('collected','derived','user_historical')
        ORDER BY ym""", (item, cc)).fetchall()
    # 同时从 retail 的 user_historical 也能拿到（method 在 derive_farmgate 会设为 collected）
    if not hist:
        # 完全没有历史：全区间用 anchor 兜底，标 forecast
        for ym in labels:
            fg = ANCHOR_USD[item][cc]
            conn.execute("""INSERT INTO livestock_farmgate
                (item,country,ym,price_usd,method,formula,source_url)
                VALUES(?,?,?,?,?,?,?)
                ON CONFLICT(item,country,ym) DO UPDATE SET
                    price_usd=excluded.price_usd, method=excluded.method,
                    formula=excluded.formula, source_url=excluded.source_url
                WHERE livestock_farmgate.method != 'collected'""",
                (item,cc,ym,round(fg,4),"forecast","anchor_only",src_url))
        return

    hist_dict = {ym: p for ym, p in hist}
    last_known_ym = hist[-1][0]
    if last_known_ym not in labels:
        last_known_ym = max((ym for ym in hist_dict if ym in labels), default=labels[0])
    last_known_idx = labels.index(last_known_ym)

    # 线性拟合最近 6 个月（或更少）
    recent = [(ym, hist_dict[ym]) for ym in labels[:last_known_idx+1] if ym in hist_dict]
    recent = recent[-6:]
    n = len(recent)
    if n >= 2:
        xs = list(range(n))
        ys = [p for _, p in recent]
        x_mean, y_mean = sum(xs)/n, sum(ys)/n
        num = sum((xs[i]-x_mean)*(ys[i]-y_mean) for i in range(n))
        den = sum((xs[i]-x_mean)**2 for i in range(n))
        slope = num / den if den else 0.0
        intercept = y_mean - slope * x_mean
        def predict(offset):
            return intercept + slope * offset
        base_text = "linear(%s..%s)" % (recent[0][0], recent[-1][0])
    else:
        slope = 0.0
        intercept = recent[0][1] if recent else ANCHOR_USD[item][cc]
        def predict(offset):
            return intercept
        base_text = "flat(%s)" % (recent[0][0] if recent else "anchor")

    # 历史区间保留已有值（不覆盖 collected）
    for ym in labels[:last_known_idx+1]:
        if ym in hist_dict:
            # 已有 collected/derived，不动
            pass
    # 预测区间：last_known_ym 之后
    for offset, ym in enumerate(labels[last_known_idx+1:], start=1):
        fg = predict(n - 1 + offset)
        # 防止价格跌至负数或过低
        floor = ANCHOR_USD[item][cc] * 0.3
        if fg < floor:
            fg = floor
        formula = "%s forecast +%dm" % (base_text, offset)
        conn.execute("""INSERT INTO livestock_farmgate
            (item,country,ym,price_usd,method,formula,source_url)
            VALUES(?,?,?,?,?,?,?)
            ON CONFLICT(item,country,ym) DO UPDATE SET
                price_usd=excluded.price_usd, method=excluded.method,
                formula=excluded.formula, source_url=excluded.source_url
            WHERE livestock_farmgate.method != 'collected'""",
            (item,cc,ym,round(fg,4),"forecast",formula,src_url))


def _gap_fill_simple(series, labels, item, cc):
    """series: {ym:(price, note)} ; 返回 {ym:(price, method, formula)}
    逻辑：
      1) 已知月直接采用（method = note，'collected' 或 'oecd_shape_anchor'）
      2) 已知月之间的断点：线性插值（method=gap_fill, linear_interp）
      3) 开头的断点：用首个已知月值（最近已知点，method=gap_fill）
      4) 结尾的断点：用末个已知月值（method=gap_fill）
      5) 完全无已知月：用 ANCHOR_USD 兜底（method=anchor）
    保证不崩溃、无 None 残留。
    """
    n = len(labels)
    # 已知月索引与价格
    known = {}  # idx -> (price, note)
    for idx, ym in enumerate(labels):
        v = series.get(ym)
        if v is not None:
            known[idx] = (v[0], v[1])
    idxs = sorted(known.keys())
    out = {}
    if not idxs:
        # 完全无数据 → 锚点
        anc = ANCHOR_USD[item][cc]
        for ym in labels:
            out[ym] = (round(anc,4), "anchor", "anchor_only")
        return out
    # 1) 已知月
    for idx in idxs:
        price, note = known[idx]
        # 真值/联网抓取(direct=collected, inverse=derived, faostat)一律锁死为 collected，
        # 使自动更新的月份经实时汇率换算成 USD 后固定不再浮动；锚点/插值(gap_fill/anchor)仍可升级。
        method = "collected" if note in ("collected", "derived", "faostat") else (note if note else "collected")
        out[labels[idx]] = (round(price,4), method, note)
    # 2) 线性插值（相邻已知月之间）
    for a, b in zip(idxs, idxs[1:]):
        if b - a <= 1:
            continue
        pa = known[a][0]; pb = known[b][0]
        for k in range(a+1, b):
            frac = (k - a) / (b - a)
            p = pa + (pb - pa) * frac
            out[labels[k]] = (round(p,4), "gap_fill", "linear_interp(%s,%s)" % (labels[a], labels[b]))
    # 3) 开头断点（0..idxs[0]-1）→ 首个已知月值
    for k in range(0, idxs[0]):
        out[labels[k]] = (round(known[idxs[0]][0],4), "gap_fill", "lead_forward(%s)" % labels[idxs[0]])
    # 4) 结尾断点（idxs[-1]+1..n-1）→ 末个已知月值
    for k in range(idxs[-1]+1, n):
        out[labels[k]] = (round(known[idxs[-1]][0],4), "gap_fill", "tail_backward(%s)" % labels[idxs[-1]])
    return out


